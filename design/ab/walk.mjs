// Play the whole A+B story by real taps, screenshot every moment, fail on errors or overflow.
import { chromium } from "/home/feryyp/.agents/skills/adaptive-ux/scripts/node_modules/playwright-core/index.mjs";
import { mkdirSync } from "node:fs";
const out = new URL("./shots/", import.meta.url).pathname; mkdirSync(out, { recursive: true });
const b = await chromium.launch({ executablePath: "/usr/bin/google-chrome" });
const p = await b.newPage({ viewport: { width: 520, height: 1040 }, deviceScaleFactor: 2 });
const errs = []; p.on("pageerror", (e) => errs.push(String(e)));
await p.goto("file://" + new URL("./index.html", import.meta.url).pathname);
let n = 0;
const shot = async (name) => { await p.waitForTimeout(550); await p.locator("#phone").screenshot({ path: `${out}${String(n++).padStart(2, "0")}-${name}.png` }); };
const tap = async (sel) => { await p.click(sel, { timeout: 3000 }).catch((e) => errs.push(`${sel}: ${e.message.split("\n")[0]}`)); await p.waitForTimeout(250); };
const as = (w) => tap(`.controls [data-as="${w}"]`);

await shot("dina-chat-open");
await tap(".plus"); await shot("dina-tray");
await tap('[data-act="share"]'); await shot("dina-share");
await tap('.sheet [data-act="closeSheet"]');
await as("ayu"); await shot("ayu-chat");
await tap(".plus"); await tap('[data-act="askSheet"]'); await shot("ayu-ask-sheet");
await tap('[data-act="cap"][data-d="100"]'); await tap('[data-act="cap"][data-d="-100"]');
await tap('.sheet [data-act="doAsk"] >> nth=1'); await shot("ayu-asked");
await as("dina"); await shot("dina-requests");
await tap('[data-act="accept"]'); await shot("dina-accepted");
await as("ayu"); await shot("ayu-hold-card");
await tap('[data-act="holdSheet"]'); await shot("ayu-paypal");
await tap('[data-act="doHold"]'); await shot("ayu-held");
await tap('[data-act="tab"][data-tab="wallet"]'); await shot("ayu-wallet-held");
await tap('[data-act="tab"][data-tab="chat"]');
await as("dina"); await tap(".plus"); await tap('[data-act="shopMode"]'); await shot("dina-shop");
await tap('[data-act="doShop"]'); await shot("dina-shop-swap");
await tap('[data-act="closeShop"]'); await shot("dina-chat-swap");
await as("bima"); await shot("bima-swap");
await tap('[data-act="swapYes"]'); await shot("bima-took");
await as("dina"); await tap(".plus"); await tap('[data-act="scan"]'); await shot("dina-receipt");
await tap('[data-act="doSettle"]'); await shot("dina-settled");
await tap('[data-act="tab"][data-tab="wallet"]'); await shot("dina-wallet");
await as("ayu"); await shot("ayu-wallet-paid");
await tap('[data-act="openPass"][data-k="ayu"]'); await shot("ayu-pass-open");
await tap('[data-act="tab"][data-tab="chat"]'); await shot("ayu-chat-end");
await tap('[data-act="home"]'); await shot("ayu-trips");
const ov = await p.evaluate(() => [...document.querySelectorAll("#phone *")].filter((e) => e.scrollWidth > e.clientWidth + 1 && getComputedStyle(e).overflowX === "visible" && e.closest(".chat,.wallet,.shop,.sheet")).length);
console.log(`${n} shots, ${errs.length} errors${errs.length ? ": " + errs.join(" | ") : ""}, overflow-suspects ${ov}`);
await b.close();
