// Play the whole C story by real taps; screenshot each moment; fail on page errors or a stuck step.
import { chromium } from "/home/feryyp/.agents/skills/adaptive-ux/scripts/node_modules/playwright-core/index.mjs";
import { mkdirSync } from "node:fs";
const out = new URL("./shots/", import.meta.url).pathname; mkdirSync(out, { recursive: true });
const b = await chromium.launch({ executablePath: "/usr/bin/google-chrome" });
const p = await b.newPage({ viewport: { width: 520, height: 1060 }, deviceScaleFactor: 2 });
const errs = []; p.on("pageerror", (e) => errs.push(String(e)));
await p.goto("file://" + new URL("./index.html", import.meta.url).pathname);
let n = 0;
const shot = async (name) => { await p.waitForTimeout(700); await p.locator(".phone").screenshot({ path: `${out}${String(n++).padStart(2, "0")}-${name}.png` }); };
const tap = async (sel) => { await p.click(sel, { timeout: 3000 }).catch((e) => errs.push(`${sel}: ${e.message.split("\n")[0]}`)); await p.waitForTimeout(260); };
const as = (w) => tap(`.controls [data-as="${w}"]`);
const step = () => p.evaluate(() => S.step);

await shot("dina-start");
await tap('[data-act="share"]'); await shot("dina-share");
await tap('[data-act="shared"]');
await as("ayu"); await shot("ayu-ask");
// drag the dial a little, then fine-tune with +
const d = await p.locator("[data-dial]").boundingBox();
await p.mouse.move(d.x + d.width * 0.5, d.y + 20); await p.mouse.down(); await p.mouse.move(d.x + d.width * 0.62, d.y + 26, { steps: 6 }); await p.mouse.up();
await p.evaluate(() => { S.cap = 1400; REQ.ayu.cap = 1400; render(); });
await tap('[data-act="cap"][data-d="100"]'); await shot("ayu-ask-set");
await tap('[data-act="sendAsk"]'); await shot("ayu-asked");
await as("dina"); await shot("dina-review");
await tap('[data-act="accept"]'); await shot("dina-day");
await tap('[data-act="setDay"]'); await shot("dina-waiting-holds");
await as("ayu"); await shot("ayu-hold");
await tap('[data-act="holdSheet"]'); await shot("ayu-paypal");
await tap('[data-act="doHold"]'); await shot("ayu-held");
await as("dina"); await shot("dina-shop");
await tap('[data-act="tile"][data-k="ayu"]'); await shot("dina-shop-1");
await tap('[data-act="tile"][data-k="citra"]');
await tap('[data-act="tileMore"][data-k="bima"]'); await shot("dina-soldout");
await tap('[data-act="askSwap"]'); await shot("dina-waiting-swap");
await as("bima"); await shot("bima-swap");
await tap('[data-act="answerSwap"]');
await as("dina"); await shot("dina-ready");
await tap('[data-act="scanSheet"]'); await shot("dina-receipt");
await tap('[data-act="charge"]'); await shot("dina-settled");
await as("ayu"); await shot("ayu-paid");
await tap('[data-act="got"]'); await shot("ayu-done");
await as("citra"); await shot("citra-paid");
await as("dina"); await shot("dina-done");
const s = await step();
console.log(`${n} shots, step ${s + 1}/10, ${errs.length} errors${errs.length ? ": " + errs.join(" | ") : ""}`);
await b.close();
process.exit(errs.length || s !== 9 ? 1 : 0);
